"""
Parse and Analyze Memory Scalability Benchmark Results.

This script processes CSV files generated by memory scalability benchmarks.
The goal is to analyze how the Resident Set Size (RSS) memory of a process
scales with the number of entities (e.g., publishers, subscribers) it contains.

The script performs the following tasks:
1.  **Data Parsing**: Reads memory usage data from all CSV files in a specified
    directory. It specifically looks for 'N' (number of entities) and 'RSS'
    (Resident Set Size in KB) columns.
2.  **Linear Regression**: Calculates a linear regression on the RSS vs. N data
    for each test case. This helps quantify the memory cost per entity. The
    script can be configured to ignore initial samples to allow for system
    stabilization.
3.  **Plotting**: Generates a single figure containing subplots for each test
    case. Each subplot shows the RSS memory vs. the number of entities, along
    with the calculated linear regression line and the R-squared value, which
    indicates how well the linear model fits the data.
4.  **Output**: Saves the generated plot as `memory_scaling_comparison.png` in
    the `parsed_results` directory.
"""

import argparse
import csv
import itertools
import os
import sys

from collections import defaultdict
from scipy.stats import linregress
from typing import Dict, Any

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt


def load_dataframe(file_path: str) -> pd.DataFrame:
    """
    Load a CSV file into a pandas DataFrame, skipping any malformed rows.

    Args:
        file_path: The path to the CSV file.

    Returns:
        A pandas DataFrame with the sanitized data.
    """

    with open(file_path, "r+", newline="") as f:
        reader = csv.reader(f, delimiter="\n")
        field_names, data = list(), defaultdict(list)

        for i, line in enumerate(reader):
            split_line = line[0].split(",")
            if i == 0:
                field_names = split_line
            else:
                if len(split_line) != len(field_names):
                    print("Skipping malformed line", i, line)
                    continue

                for i in range(len(split_line)):
                    if i > 0 and field_names[i] != split_line[i]:
                        data[field_names[i]].append(np.float64(split_line[i]))

    return pd.DataFrame(data)


def parse_memory_results(directory: str) -> Dict[str, Dict[str, np.ndarray]]:
    """
    Parse all memory benchmark CSV files in a given directory.

    Args:
        directory: The directory containing the memory result CSV files.

    Returns:
        A dictionary where keys are filenames and values are dictionaries
        containing 'N', 'RSS', and 'DELTA' data as NumPy arrays.
    """
    memory_data = {}

    # Iterate through all CSV files in the directory
    for file_name in os.listdir(directory):
        if file_name.endswith(".csv"):
            file_path = os.path.join(directory, file_name)

            df = load_dataframe(file_path)

            # Extract N, RSS, and DELTA columns
            if all(col in df.columns for col in ["N", "RSS", "DELTA"]):
                memory_data[file_name] = {
                    "N": df["N"].values,
                    "RSS": df["RSS"].values / 1024,  # Convert KB to MB
                    "DELTA": df["DELTA"].values,
                }
            else:
                print(f"Warning: Missing expected columns in {file_name}")

    return memory_data


def calculate_regressions(
    memory_data: Dict[str, Dict[str, np.ndarray]],
    ignore_first_n: int = 0,
    num_samples: int = 3,
) -> Dict[str, Dict[str, float]]:
    """
    Calculate linear regression for each dataset in memory_data.

    This function fits a line to the (N, RSS) data points to determine how
    memory usage scales with the number of entities.

    Args:
        memory_data: A dictionary containing the parsed memory data.
        ignore_first_n: The number of initial samples to ignore, allowing the
                        system's memory usage to stabilize.
        num_samples: The number of subsequent samples to use for the regression.

    Returns:
        A dictionary containing the regression results (slope, intercept, r2)
        for each file.
    """
    regression_results = {}

    for file_name, data in memory_data.items():
        N, RSS = data["N"], data["RSS"]

        if len(N) <= ignore_first_n:
            print(
                f"Skipping {file_name} due to insufficient data points after ignoring the first {ignore_first_n}."
            )
            continue

        N_reg = N[ignore_first_n:]
        RSS_reg = RSS[ignore_first_n:]

        if num_samples is not None:
            N_reg = N_reg[:num_samples]
            RSS_reg = RSS_reg[:num_samples]

        slope, intercept, r_value, _, std_err = linregress(N_reg, RSS_reg)
        regression_line = slope * N_reg + intercept

        regression_results[file_name] = {
            "slope": slope,
            "intercept": intercept,
            "r2": r_value**2,  # Return R²
        }

    return regression_results


def plot_memory_scaling(
    memory_data: Dict[str, Any],
    regression_results: Dict[str, Any],
    output_file: str,
    ignore_first_n_plot: int = 2,
    omit_last_m_plot: int = 1,
    show_plot: bool = False,
):
    """
    Generate and save a plot of RSS memory vs. number of entities (N).

    Each input file is plotted on a separate subplot. The plot includes the raw
    data points and the calculated linear regression line.

    Args:
        memory_data: Parsed memory data.
        regression_results: Calculated regression results.
        output_file: Path to save the output plot image.
        ignore_first_n_plot: Number of initial data points to exclude from the plot.
        omit_last_m_plot: Number of final data points to exclude from the plot.
        show_plot: If True, display the plot interactively.
    """
    num_plots = len(memory_data)
    if num_plots == 0:
        print("No data to plot.")
        return

    num_columns = 3
    num_rows = (num_plots + num_columns - 1) // num_columns

    fig, axes = plt.subplots(num_rows, num_columns, figsize=(15, 5 * num_rows))
    axes = axes.flatten()

    # Generate dynamic color pairs using a colormap
    color_map = plt.colormaps["tab10"].colors
    color_pairs = list(itertools.combinations(color_map, 2))

    for idx, (file_name, data) in enumerate(memory_data.items()):
        N, RSS = data["N"], data["RSS"]

        # Skip first `ignore_first_n_plot` entries
        if len(N) <= ignore_first_n_plot:
            print(
                f"Skipping {file_name} due to insufficient data points after ignoring the first {ignore_first_n_plot}."
            )
            continue

        N_plot = N[ignore_first_n_plot:]
        RSS_plot = RSS[ignore_first_n_plot:]

        # Further omit the last `omit_last_m_plot` items
        N_plot = N_plot[:-omit_last_m_plot] if omit_last_m_plot > 0 else N_plot
        RSS_plot = RSS_plot[:-omit_last_m_plot] if omit_last_m_plot > 0 else RSS_plot

        # Get regression results
        regression_result = regression_results.get(file_name)
        if regression_result:
            slope = regression_result["slope"]
            intercept = regression_result["intercept"]
            r2 = regression_result["r2"]

            # Extend the regression line over the entire range of the plot
            N_extended = np.linspace(
                N_plot[0], N_plot[-1], 100
            )  # 100 points for smooth line
            regression_line_extended = slope * N_extended + intercept

            # Get color pair for the current plot
            data_color, fit_color = color_pairs[idx % len(color_pairs)]

            ax = axes[idx]
            # Plot the actual data
            ax.plot(
                N_plot, RSS_plot, "o-", color=data_color, label=f"{file_name} (data)"
            )

            # Plot the extended regression line
            ax.plot(
                N_extended,
                regression_line_extended,
                "--",
                color=fit_color,
                label=f"{file_name} (fit, R²={r2:.2f})",
            )

            # Add labels, title, and legend
            ax.set_xlabel("Number of Entities (N)")
            ax.set_ylabel("RSS Memory (MB)")
            ax.set_title(f"RSS Memory Scaling for {file_name}")
            ax.legend(loc="upper left")
            ax.grid(True, linestyle="--", alpha=0.5)

    # Hide any unused subplots
    for idx in range(len(memory_data), len(axes)):
        fig.delaxes(axes[idx])

    plt.tight_layout()
    plt.savefig(output_file, bbox_inches="tight")
    if show_plot:
        plt.show()


def main():
    """Main function to parse arguments and trigger memory scalability analysis."""

    # Create the argument parser
    parser = argparse.ArgumentParser(description="Memory scalability result parser")

    # Add a required positional argument for the results directory path
    parser.add_argument(
        "results_directory",
        type=str,
        help="The path where the results files will be searched and the output will be saved.",
    )

    parser.add_argument(
        "--show-plot",
        action="store_true",
        help="Show the generated memory plots (optional).",
    )

    # Parse the arguments
    args = parser.parse_args()

    # Verify memory_results directory exists
    memory_data_dir = args.results_directory
    if not str.endswith(memory_data_dir, "memory_test"):
        memory_data_dir = os.path.join(memory_data_dir, "memory_test")
    if not os.path.exists(memory_data_dir):
        print(f"Error: Directory '{memory_data_dir}' not found.")
        sys.exit(1)

    # Parse memory_results
    print("Parsing memory results...")
    memory_data = parse_memory_results(memory_data_dir)

    # Calculate regression results
    print("Calculating regressions...")
    try:
        regression_results = calculate_regressions(
            memory_data, ignore_first_n=3, num_samples=3
        )
    except TypeError as te:
        print("Error parsing memory results. ", te)

    # Generate plot
    print("Generating memory_scaling_comparison.png...")

    parsed_results_directory = os.path.join(args.results_directory, "parsed_results")
    os.makedirs(parsed_results_directory, exist_ok=True)

    output_plot = os.path.join(
        parsed_results_directory, "memory_scaling_comparison.png"
    )
    plot_memory_scaling(
        memory_data,
        regression_results,
        output_plot,
        ignore_first_n_plot=0,
        omit_last_m_plot=1,
        show_plot=args.show_plot,
    )

    print(f"✅ Processing completed. Plot saved to: {output_plot}")


if __name__ == "__main__":
    main()
