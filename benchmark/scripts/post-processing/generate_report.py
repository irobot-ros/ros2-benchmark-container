        "In the context of this test, the null hypothesis states that a multi-process application using RMW "
        "has equal or higher CPU usage and latency compared to an equivalent single-process application.<br/><br/>"
        "If the p-value is low (typically ≤ 0.05), there is enough evidence to reject the null hypothesis and conclude "
