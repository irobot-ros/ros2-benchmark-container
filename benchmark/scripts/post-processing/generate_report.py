def main() -> None:
    # Create the argument parser
    parser = argparse.ArgumentParser(
        description="""
This script generates a PDF report ('report.pdf') from the post-process data generated by the benchmarks.

The report is saved in the current working directory.

Usage:
    python generate_report.py <results_directory>  

Arguments:
    results_directory (str): Path where the plots files are located.       
    --output, -o (str, optional): Directory where the report will be saved. Defaults to the current working directory.                      
    --skip-long-tests (flag, optional): If present, skips processing of long-duration test results.
"""
    )

    # Add a required positional argument for the results directory path
    parser.add_argument(
        "results_directory",
        type=str,
        help="The path where the results files will be searched and the output will be saved.",
    )

    # Add an optional argument for the output directory (default is current working directory)
    parser.add_argument(
        "--output",
        "-o",
        type=str,
        default=os.getcwd(),
        help="Directory where the report will be saved. Defaults to the current working directory.",
    )

    # Optional flag to skip long-duration tests
    parser.add_argument(
        "--skip-long-tests",
        action="store_true",
        help="If set, skips processing of long-duration test results.",
    )

    # Parse the arguments
    args = parser.parse_args()

    if not os.path.isdir(args.results_directory):
        print(f"Error: '{args.results_directory}' is not a valid directory.")
        sys.exit(1)

    parsed_results_directory = os.path.join(args.results_directory, "parsed_results")
    os.makedirs(parsed_results_directory, exist_ok=True)

    # Generate report
    results_date = os.path.basename(os.path.normpath(args.results_directory)).replace(
        "results_", ""
    )
    report_path = os.path.join(args.output, f"report_{results_date}.pdf")
    print(f"Generating report {report_path}")
    generate_report(parsed_results_directory, report_path, args.skip_long_tests)


if __name__ == "__main__":
    main()
