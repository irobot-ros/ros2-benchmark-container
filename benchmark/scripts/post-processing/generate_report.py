# --- ReportLab Style Definitions ---
GLOBAL_STYLES = getSampleStyleSheet()
TITLE_STYLE = "Title"
TEST_SECTION_STYLE = "Heading1"
TEST_SUBSECTION_STYLE = "Heading2"
TEST_DESCRIPTION_STYLE = "Heading3"
NORMAL_TEXT_STYLE = "Normal"


# --- PDF Generation Helper Functions ---
def _add_styled_paragraph(
    elements: List[Any],
    text: str,
    style: str,
    spacer_height: float = 0,
):
    """Helper to add a styled paragraph and an optional spacer."""
    elements.append(Paragraph(text, GLOBAL_STYLES[style]))
    if spacer_height > 0:
        elements.append(Spacer(1, spacer_height))


def add_title(elements: List[Any], text: str):
    """Adds a main title to the list of elements."""
    _add_styled_paragraph(elements, text, TITLE_STYLE, 10)


def add_section_title(elements: List[Any], text: str):
    """Adds a section title to the list of elements."""
    _add_styled_paragraph(elements, text, TEST_SECTION_STYLE)


def add_description_paragraph(elements: List[Any], text: str):
    """Adds a description paragraph to the list of elements."""
    _add_styled_paragraph(elements, text, TEST_DESCRIPTION_STYLE, 10)


def add_subsection_title(elements: List[Any], text: str):
    """Adds a subsection title to the list of elements."""
    _add_styled_paragraph(elements, text, TEST_SUBSECTION_STYLE, 20)


def add_normal_text(elements: List[Any], text: str, spacer_height: float = 20.0):
    """Adds a normal text paragraph to the list of elements, followed by a spacer."""
    _add_styled_paragraph(elements, text, NORMAL_TEXT_STYLE, spacer_height)


def load_plot(plots_directory: str, filename: str, scale: float = 0.45) -> Image:
    """
    Loads a plot image from a file and scales it for the report.

    Args:
        plots_directory: The directory where the plot image is located.
        filename: The filename of the plot image.
        scale: The scaling factor for the image.

    Returns:
        A ReportLab `Image` object containing the imported plot.
    """
    if not filename.endswith(".png"):
        filename += ".png"
    img_path = os.path.join(plots_directory, filename)

    if not os.path.exists(img_path):
        raise FileNotFoundError(f"File not found: {img_path}")

    img = Image(img_path)
    # Scale the image to fit the page
    img._restrictSize(img.imageWidth * scale, img.imageHeight * scale)
    return img


def add_plot(
    elements: List[Any], plots_directory: str, filename: str, scale: float = 0.45
):
    """
    Adds a plot image to the list of elements.

    Args:
        elements: The list of PDF content elements.
        plots_directory: The directory containing the plot images.
        filename: The filename of the plot image.
        scale: The scaling factor for the image.
    """
    try:
        img = load_plot(plots_directory, filename, scale)
        elements.append(img)
        elements.append(Spacer(1, 20))
    except FileNotFoundError as e:
        print(f"Error loading plot {filename}: {e}")


def add_multi_plot(
    elements: List[Any],
    results_dir: str,
    plot_filenames: List[str],
    scale: float = 0.45,
):
    """
    Adds plot images that are divided into multiple files due to exceeding the number of subplots per figure.

    Args:
        elements: The list of content to append to.
        results_dir: The base directory where the plots are located.
        plot_filenames: A list of base filenames for the plots.
        scale: The scaling factor for the images.
    """
    for base_filename in plot_filenames:
        # Create a glob pattern to match base + _optional_suffix
        pattern = os.path.join(results_dir, f"{base_filename}*")
        matching_files = sorted(glob.glob(pattern))
        for filepath in matching_files:
            try:
                filename = os.path.basename(filepath)
                add_plot(elements, results_dir, filename, scale)
            except FileNotFoundError as e:
                print(f"Error: {e}")  # Log and continue


def parse_date_from_dirname(dir: str) -> str:
    """
    Extracts a formatted date string from a directory name.

    Args:
        dir: The directory name containing the date in the format 'DD_MM_YY_HHhMM'.

    Returns:
        A formatted date string (e.g., 'DD-MM-YY - HH:MM') or an empty string if not found.
    """
    match = re.search(r"(\d{2})_(\d{2})_(\d{2})_(\d{2}h\d{2})", dir)
    # Output in format DD-MM-YY HH:SS
    return (
        f"{match.group(1)}-{match.group(2)}-{match.group(3)} - {match.group(4).replace('h', ':')}"
        if match
        else ""
    )


def create_styled_table(data: List[List[Any]]) -> Optional[Table]:
    """
    Creates a ReportLab `Table` object with standard project styling.

    Args:
        data: A list of lists where the first list is the header and the rest are the rows.

    Returns:
        A styled `Table` object, or None if the data contains only a header.
    """
    if len(data) == 1:  # Only headers, no actual data
        return None
    table = Table(data)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.grey),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 10),
                ("GRID", (0, 0), (-1, -1), 1, colors.black),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
            ]
        )
    )
    return table


def load_and_group_latency_comparison_csv(csv_path: str) -> Dict[str, List[List[Any]]]:
    """
    Loads CSV data from the specified file and group it by the test case column.

    Args:
        csv_path: The path to the CSV file.

    Returns:
       A dictionary with the lists of rows grouped by test case.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"CSV file not found: {csv_path}")

    # Read CSV data
    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f, delimiter=";")
        data = list(reader)

    # Group rows by the 'test_case' column
    grouped_data = defaultdict(list)
    for row in data[1:]:  # Skip the header row
        test_case = row[0]
        grouped_data[test_case].append(row[1:])  # Append the rest of the row

    return grouped_data


def create_tables_from_groups(
    grouped_data: Dict[str, List[List[Any]]],
) -> Dict[str, Table]:
    """
    Creates a styled table for each group of data, grouped by each test case.

    Args:
        grouped_data: A dictionary where the keys are test case values, and the values are lists of rows.

    Returns:
        dict: A dictionary with the Table objects created from the grouped data by each test case.
    """
    tables = {}
    for test_case, rows in grouped_data.items():
        headers = [
            "payload",
            "multi_std_dev",
            "multi_mean",
            "single_std_dev",
            "single_mean",
            "p_value",
        ]
        # Add the header to the rows and pass to create_styled_table function
        tables[test_case] = create_styled_table([headers] + rows)
    return tables


def load_csv_as_table(csv_path: str) -> Table:
    """
    Loads a table from a CSV file in the given directory.

    Args:
        csv_path (str): Path to the CSV file containing the table data.

    Returns:
        A styled `Table` object containing the data from the CSV file.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"CSV file not found: {csv_path}")

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f, delimiter=";")  # Use ';' as the delimiter
        data = list(reader)
    return create_styled_table(data)


def load_regression_tables(csv_path: str, ros_interface: str) -> Tuple[Table, Table]:
    """
    Loads and parses a CSV file containing linear regression results for different RMW vendors
    under single and multi-process configurations.

    The function reads a CSV file where each row includes the process type, vendor name,
    r-squared value, and slope. It separates the data into two tables: one for single-process
    and one for multi-process results.

    Args:
        csv_path: Path to the CSV file containing the regression results.
        ros_interface: The ROS interface type (e.g., 'pub-sub' or 'cli-srv')

    Returns:
        A tuple containing two `Table` objects: (single_process_table, multi_process_table).
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"CSV file not found: {csv_path}")

    single_process_data = [["RMW", "r-squared", "slope"]]  # Header
    multi_process_data = [["RMW", "r-squared", "slope"]]  # Header

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f, delimiter=";")
        next(reader)  # Skip header row

        for row in reader:
            parts = row[0].split("/")
            # Check if the row has the expected number of parts
            if len(parts) == 3:
                row_interface, process_type, vendor = parts
                if row_interface != ros_interface:
                    continue
            elif len(parts) == 2:
                process_type, vendor = parts
            else:
                print(f"Skipping invalid row: {row}")
                continue
            if "single_process" in process_type:
                single_process_data.append([vendor, row[1], row[2]])
            elif "multi_process" in process_type:
                multi_process_data.append([vendor, row[1], row[2]])
    return create_styled_table(single_process_data), create_styled_table(
        multi_process_data
    )


def get_supported_rmws(csv_path: str) -> List[str]:
    """
    Retrieves a list of supported ROS Middleware (RMW) configurations from the metrics csv file.

    Args:
        csv_path: The path to the directory containing the csv file.

    Returns:
        A sorted list of unique RMW names.
    """
    rmw_list = []

    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"CSV file not found: {csv_path}")

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f, delimiter=";")
        next(reader)  # Skip header row

        for row in reader:
            # Get the 'RMW' column value and split the path to get the RMW name
            parts = row[0].split("/")
            rmw_name = parts[2].split("_")[0]
            if rmw_name not in rmw_list:
                rmw_list.append(rmw_name)
    return sorted(rmw_list)


def generate_report(
    results_dir: str, output_filename: str, skip_long_tests: bool
) -> None:

    def _load_or_exit(loader_func, *args, **kwargs):
        """Helper to load data using a loader function or exit on FileNotFoundError."""
        try:
            return loader_func(*args, **kwargs)
        except FileNotFoundError as e:
            print(
                f"Error: {e}. Process cannot continue. Ensure all expected files are present."
            )
            sys.exit(1)

    # Create a landscape PDF with custom margins
    doc = SimpleDocTemplate(
        output_filename,
        pagesize=A4,
        leftMargin=50,  # Set left margin
        rightMargin=50,  # Set right margin
        topMargin=30,  # Set top margin
        bottomMargin=30,  # Set bottom margin
    )
