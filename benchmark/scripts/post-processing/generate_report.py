"""
Generate a Comprehensive PDF Report from Benchmark Results.

This script serves as the final step in the post-processing pipeline. It gathers all
the analyzed data, including plots and statistical summaries from CSV files, and
compiles them into a single, well-structured PDF document.

The report includes:
- An introduction with system information and a list of tested RMWs.
- Detailed sections for different test categories (Topics, Services, Actions).
- Explanations for each specific test case.
- Tables showing statistical results (e.g., from linear regressions).
- The plots generated by other analysis scripts.
"""

